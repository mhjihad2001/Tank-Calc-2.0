  fun formatLossReportCsv(
    report: LossReport,
    unit: UnitType = UnitType.LITRES,
    settings: AppSettings? = null
  ): String {
    val durationHours = report.durationHours
    val hours = durationHours.toInt()
    val mins = ((durationHours - hours) * 60).toInt()
    val genTime = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.getDefault()).format(Date())
    val cleanReportId = "LR-" + report.id.replace("-", "").take(12).uppercase()

    return buildString {
      appendLine("Refinery / Plant,Condensate Fractionation Plant")
      appendLine("Report Title,CONDENSATE FRACTIONATION PROCESS LOSS REPORT")
      appendLine("Calculation Mode,${if (report.mode == CalculationMode.TEMP_30C) "Standard (30 °C, ASTM D1250-80)" else "Natural (Ambient)"}")
      appendLine("Period,${report.startTime} to ${report.endTime}")
      appendLine("Duration,${hours}h ${mins}m (${report.durationHours} hours)")
      appendLine("Generated on,$genTime")
      appendLine("Report ID,$cleanReportId")
      appendLine("Prepared by,Process Engineer")
      appendLine("Status Flag,${report.flag}")
      appendLine("Active Display Unit,${UnitUtils.unitLabel(unit)}")
      appendLine("Total Feed,${UnitUtils.toDisplay(report.totalFeed, unit)}")
      appendLine("Total Product,${UnitUtils.toDisplay(report.totalProduct, unit)}")
      appendLine("Loss,${UnitUtils.toDisplay(report.loss, unit)}")
      appendLine("Loss %,${report.lossPercent}")
      appendLine("Yield %,${report.yieldPercent}")
      appendLine("Status Flag,${report.flag}")
      appendLine("Feed Rate,${UnitUtils.toDisplay(report.feedRatePerHour, unit)}")
      appendLine("Product Rate,${UnitUtils.toDisplay(report.productRatePerHour, unit)}")
      appendLine("Loss Rate,${UnitUtils.toDisplay(report.lossRatePerHour, unit)}")
      appendLine()
      if (report.productYields.isNotEmpty()) {
        appendLine("PRODUCT YIELD TABLE")
        appendLine("Product,Short Code,Category,Tanks,Quantity Produced,Feed %,Total Product %")
        report.productYields.forEach { py ->
          val qty = UnitUtils.toDisplay(py.productMade, unit)
          val pctF = py.percentOfFeed?.let { String.format(Locale.US, "%.2f", it) } ?: ""
          val pctP = String.format(Locale.US, "%.2f", py.percentOfTotalProduct)
          val tanksStr = "\"${py.tankNames.joinToString(", ")}\""
          appendLine("\"${py.productName}\",\"${py.shortCode}\",\"${py.category}\",$tanksStr,$qty,$pctF,$pctP")
        }
        val totF = report.totalProductPercent?.let { String.format(Locale.US, "%.2f", it) } ?: ""
        val lossF = report.lossPercentOnFeed?.let { String.format(Locale.US, "%.2f", it) } ?: ""
        appendLine("Total Product % on Feed,$totF")
        appendLine("Process Loss % on Feed,$lossF")
        appendLine()
      }
      if (report.feedTankRatios.isNotEmpty()) {
        appendLine("FEED TANK RATIO TABLE")
        appendLine("Tank Name,Feed Consumed,% of Total Feed")
        report.feedTankRatios.forEach { ftr ->
          val cStr = UnitUtils.toDisplay(ftr.feedConsumed, unit)
          val pctStr = ftr.percentOfTotalFeed?.let { String.format(Locale.US, "%.2f", it) } ?: ""
          appendLine("\"${ftr.tankName}\",$cStr,$pctStr")
        }
        appendLine()
      }
      appendLine("Tank Name,Type,Initial TOV,Final TOV,Effective Initial TOV,Additions,Net Quantity,Density@15,Init Temp,Final Temp")
      report.feedTanks.forEach {
        appendLine("${it.tankName},Feed,${UnitUtils.toDisplay(it.initialTov, unit)},${UnitUtils.toDisplay(it.finalTov, unit)},${UnitUtils.toDisplay(it.initialTov, unit)},${UnitUtils.toDisplay(it.receivingAmount, unit)},${UnitUtils.toDisplay(it.netQuantity, unit)},${it.density15 ?: ""},${it.initialTemp ?: ""},${it.finalTemp ?: ""}")
      }
      report.productTanks.forEach {
        val effInit = it.effectiveInitialTov ?: it.initialTov
        appendLine("${it.tankName},Product,${UnitUtils.toDisplay(it.initialTov, unit)},${UnitUtils.toDisplay(it.finalTov, unit)},${UnitUtils.toDisplay(effInit, unit)},${UnitUtils.toDisplay(it.blendingAmount + it.deliveryAmount, unit)},${UnitUtils.toDisplay(it.netQuantity, unit)},${it.density15 ?: ""},${it.initialTemp ?: ""},${it.finalTemp ?: ""}")
      }
      report.blendingTanks.forEach {
        val effInit = it.effectiveInitialTov ?: it.initialTov
        appendLine("${it.tankName},Blending,${UnitUtils.toDisplay(it.initialTov, unit)},${UnitUtils.toDisplay(it.finalTov, unit)},${UnitUtils.toDisplay(effInit, unit)},${UnitUtils.toDisplay(it.deliveryAmount, unit)},${UnitUtils.toDisplay(it.netQuantity, unit)},${it.density15 ?: ""},${it.initialTemp ?: ""},${it.finalTemp ?: ""}")
      }
      appendLine()
      appendLine("Footer,Generated by Tank Calc | Developed by Meherab Hossain Jihad")
    }
  }

  fun exportLossReportCsvFile(
    context: Context,
    report: LossReport,
    unit: UnitType = UnitType.LITRES,
    settings: AppSettings? = null
  ): Intent? {
    return try {
      val csvData = formatLossReportCsv(report, unit, settings)
      val timeStamp = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.getDefault()).format(Date())
      val file = File(context.cacheDir, "Process_Loss_Report_$timeStamp.csv")
      file.writeText(csvData, Charsets.UTF_8)
      val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file)
      Intent(Intent.ACTION_SEND).apply {
        type = "text/csv"
        putExtra(Intent.EXTRA_STREAM, uri)
        putExtra(Intent.EXTRA_SUBJECT, "Process Loss Report (${report.startTime} to ${report.endTime})")
        addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
      }
    } catch (e: Exception) {
      null
    }
  }

