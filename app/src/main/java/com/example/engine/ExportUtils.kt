  fun formatCruActivityReport(record: CruActivityRecord): String {
    return buildString {
      appendLine("=== CRU WAIT & ACTIVITY REPORT ===")
      appendLine("Date & Time: ${record.dateTime}")
      if (record.runDay.isNotBlank()) appendLine("Run Day / Cycle: ${record.runDay}")
      appendLine("-----------------------------------------")
      appendLine("OPERATING CONDITIONS:")
      appendLine("• RON Clear:                  ${"%.1f".format(record.ron)}")
      appendLine("• Feed Index (A+0.85N):       ${"%.1f".format(record.naphthenesAromatics)} vol %")
      appendLine("• Reactor Pressure:           ${"%.2f".format(record.pressure)} ${record.pressureUnit}")
      appendLine("• WHSV:                       ${"%.2f".format(record.whsv)} hr⁻¹")
      appendLine("• Feed MABP:                  ${"%.1f".format(record.mabp)} °C")
      appendLine("-----------------------------------------")
      appendLine("WAIT ANALYSIS:")
      appendLine("• Actual WAIT:                ${"%.2f".format(record.actualWait)} °C")
      appendLine("• SOR WAIT (base @ref):       ${"%.2f".format(record.sorWaitBase)} °C")
      appendLine("  - ΔT Pressure:              ${if (record.deltaPressure >= 0) "+" else ""}${"%.2f".format(record.deltaPressure)} °C")
      appendLine("  - ΔT WHSV:                  ${if (record.deltaWhsv >= 0) "+" else ""}${"%.2f".format(record.deltaWhsv)} °C")
      appendLine("  - ΔT MABP:                  ${if (record.deltaMabp >= 0) "+" else ""}${"%.2f".format(record.deltaMabp)} °C")
      appendLine("• Corrected SOR WAIT:         ${"%.2f".format(record.correctedSorWait)} °C")
      appendLine("• Activity Loss (Deact.):     ${if (record.activityLoss >= 0) "+" else ""}${"%.2f".format(record.activityLoss)} °C")
      if (record.remarks.isNotBlank()) {
        appendLine("-----------------------------------------")
        appendLine("Remarks: ${record.remarks}")
      }
      appendLine("=========================================")
      appendLine("Generated by Tank Calc | Developed by Meherab Hossain Jihad")
    }
  }

  fun formatCruActivityCsv(records: List<CruActivityRecord>): String {
    return buildString {
      appendLine("Date & Time,Run Day,RON Clear,A+0.85N (vol%),Pressure,Pressure Unit,WHSV (hr-1),MABP (C),Actual WAIT (C),SOR WAIT Base (C),Corrected SOR WAIT (C),Activity Loss (C),Remarks")
      records.forEach { r ->
        appendLine("\"${r.dateTime}\",\"${r.runDay}\",${r.ron},${r.naphthenesAromatics},${r.pressure},\"${r.pressureUnit}\",${r.whsv},${r.mabp},${r.actualWait},${r.sorWaitBase},${r.correctedSorWait},${r.activityLoss},\"${r.remarks.replace("\"", "\"\"")}\"")
      }
      appendLine()
      appendLine("Generated by Tank Calc | Developed by Meherab Hossain Jihad")
    }
  }

