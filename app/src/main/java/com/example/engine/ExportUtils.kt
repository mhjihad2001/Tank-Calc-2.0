  fun getPeriodReportTitle(startTime: String, endTime: String): String {
    return try {
      val parser = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.getDefault())
      val d1 = parser.parse(startTime.trim())
      val d2 = parser.parse(endTime.trim())
      if (d1 != null && d2 != null) {
        val dayFmt = SimpleDateFormat("dd MMM yyyy", Locale.getDefault())
        val timeFmt = SimpleDateFormat("HH:mm", Locale.getDefault())
        val day1 = dayFmt.format(d1)
        val day2 = dayFmt.format(d2)
        if (day1 == day2) {
          "Loss Report - $day1 (${timeFmt.format(d1)} to ${timeFmt.format(d2)})"
        } else {
          val shortDayFmt = SimpleDateFormat("dd MMM", Locale.getDefault())
          "Loss Report - ${shortDayFmt.format(d1)} ${timeFmt.format(d1)} to ${dayFmt.format(d2)} ${timeFmt.format(d2)}"
        }
      } else {
        "Loss Report - $startTime to $endTime"
      }
    } catch (e: Exception) {
      "Loss Report - $startTime to $endTime"
    }
  }

  fun formatLossReport(
    report: LossReport,
    unit: UnitType = UnitType.LITRES,
    settings: AppSettings? = null
  ): String {
    val durationHours = report.durationHours
    val hours = durationHours.toInt()
    val mins = ((durationHours - hours) * 60).toInt()
    val genTime = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.getDefault()).format(Date())
    val cleanReportId = "LR-" + report.id.replace("-", "").take(12).uppercase()

    return buildString {
      appendLine("=========================================================")
      appendLine("                   PARTEX PETRO LTD.")
      appendLine("             CONDENSATE FRACTIONATION PLANT")
      appendLine("      CONDENSATE FRACTIONATION PROCESS LOSS REPORT")
      appendLine("=========================================================")
      appendLine("Company: ${settings?.companyName ?: "PARTEX PETRO LTD."}")
      appendLine("Refinery / Plant: ${settings?.plantName ?: "Condensate Fractionation Plant"}")
      appendLine("Report Title: CONDENSATE FRACTIONATION PROCESS LOSS REPORT")
      appendLine("Mode: ${if (report.mode == CalculationMode.TEMP_30C) "Standard (30 °C, ASTM D1250-80)" else "Natural (Ambient)"}")
      appendLine("Period: ${report.startTime} to ${report.endTime} (Duration: ${hours}h ${mins}m)")
      appendLine("Generated on: $genTime")
      appendLine("Report ID: $cleanReportId")
      appendLine("Prepared by: ${settings?.signaturePreparedBy ?: "Process Engineer"}")
      appendLine("Status Flag: ${report.flag}")
      appendLine("Active Display Unit: ${UnitUtils.unitLabel(unit)}")
      appendLine("---------------------------------------------------------")
      appendLine("Total Feed Consumed: ${UnitUtils.formatVolume(report.totalFeed, unit, settings = settings)}")
      appendLine("Total Product Produced: ${UnitUtils.formatVolume(report.totalProduct, unit, settings = settings)}")
      val lossLabel = if (report.loss < 0) "Process Gain (+)" else "Process Loss (-)"
      val absLoss = abs(report.loss)
      appendLine("$lossLabel: ${UnitUtils.formatVolume(absLoss, unit, settings = settings)} (${String.format(Locale.US, "%.2f", report.lossPercent)}%)")
      appendLine("Refinery Yield: ${String.format(Locale.US, "%.2f", report.yieldPercent)}%")
      appendLine("Feed Rate: ${UnitUtils.formatRate(report.feedRatePerHour, unit, settings = settings)}")
      appendLine("Product Rate: ${UnitUtils.formatRate(report.productRatePerHour, unit, settings = settings)}")
      appendLine("Loss Rate: ${UnitUtils.formatRate(report.lossRatePerHour, unit, settings = settings)}")
      appendLine("---------------------------------------------------------")
      appendLine("FEED TANKS:")
      report.feedTanks.forEach { e ->
        val initV = UnitUtils.formatVolume(e.initialTov, unit, settings = settings)
        val finalV = UnitUtils.formatVolume(e.finalTov, unit, settings = settings)
        val recV = UnitUtils.formatVolume(e.receivingAmount, unit, settings = settings)
        val netV = UnitUtils.formatVolume(e.netQuantity, unit, settings = settings)
        appendLine("• ${e.tankName}: Init $initV -> Final $finalV | Rec: $recV | Net: $netV")
        if (report.mode == CalculationMode.TEMP_30C && e.density15 != null) {
          val init30 = UnitUtils.formatVolume(e.initialTov30 ?: 0.0, unit, settings = settings)
          val final30 = UnitUtils.formatVolume(e.finalTov30 ?: 0.0, unit, settings = settings)
          appendLine("  [30°C: Init $init30 (VCF ${e.initialVcf}), Final $final30 (VCF ${e.finalVcf})]")
        }
      }
      appendLine("PRODUCT TANKS:")
      report.productTanks.forEach { e ->
        val initV = UnitUtils.formatVolume(e.initialTov, unit, settings = settings)
        val finalV = UnitUtils.formatVolume(e.finalTov, unit, settings = settings)
        val blendV = UnitUtils.formatVolume(e.blendingAmount, unit, settings = settings)
        val delV = UnitUtils.formatVolume(e.deliveryAmount, unit, settings = settings)
        val netV = UnitUtils.formatVolume(e.netQuantity, unit, settings = settings)
        appendLine("• ${e.tankName}: Init $initV -> Final $finalV | Blend: $blendV, Del: $delV | Net: $netV")
        if (report.mode == CalculationMode.TEMP_30C && e.density15 != null) {
          val init30 = UnitUtils.formatVolume(e.initialTov30 ?: 0.0, unit, settings = settings)
          val final30 = UnitUtils.formatVolume(e.finalTov30 ?: 0.0, unit, settings = settings)
          appendLine("  [30°C: Init $init30 (VCF ${e.initialVcf}), Final $final30 (VCF ${e.finalVcf})]")
        }
        if (e.blendedInAmount > 0) {
          appendLine("  • Effective Initial TOV: ${UnitUtils.formatVolume(e.effectiveInitialTov ?: (e.initialTov + e.blendedInAmount), unit, settings = settings)} (+${UnitUtils.formatVolume(e.blendedInAmount, unit, settings = settings)} blended in)")
        }
      }
      if (report.blendingTanks.isNotEmpty()) {
        appendLine("BLENDING TANKS:")
        report.blendingTanks.forEach { e ->
          val initV = UnitUtils.formatVolume(e.initialTov, unit, settings = settings)
          val finalV = UnitUtils.formatVolume(e.finalTov, unit, settings = settings)
          val delV = UnitUtils.formatVolume(e.deliveryAmount, unit, settings = settings)
          val netV = UnitUtils.formatVolume(e.netQuantity, unit, settings = settings)
          val blendInV = UnitUtils.formatVolume(e.blendedInAmount, unit, settings = settings)
          val effInitV = UnitUtils.formatVolume(e.effectiveInitialTov ?: (e.initialTov + e.blendedInAmount), unit, settings = settings)
          appendLine("• ${e.tankName}: Init $initV, Blended In $blendInV, Effective Init $effInitV, Final $finalV, Del: $delV | Net: $netV")
        }
      }
      if (report.productYields.isNotEmpty()) {
        appendLine("---------------------------------------------------------")
        appendLine("PRODUCT YIELD SUMMARY (Feed Basis):")
        report.productYields.forEach { py ->
          val qtyStr = UnitUtils.formatVolume(py.productMade, unit, settings = settings)
          val pctStr = if (py.percentOfFeed != null) String.format(Locale.US, "%.2f%%", py.percentOfFeed) else "-"
          val tanksList = py.tankNames.joinToString(", ")
          appendLine("• ${py.productName} (${py.shortCode}): $qtyStr ($pctStr of feed) [Tanks: $tanksList]")
        }
        val totProdPctStr = if (report.totalProductPercent != null) String.format(Locale.US, "%.2f%%", report.totalProductPercent) else "-"
        val lossPctStr = if (report.lossPercentOnFeed != null) String.format(Locale.US, "%.2f%%", report.lossPercentOnFeed) else "-"
        appendLine("Total Product: $totProdPctStr of feed | Process Loss: $lossPctStr of feed")
      }
      if (report.feedTankRatios.isNotEmpty()) {
        appendLine("---------------------------------------------------------")
        appendLine("FEED TANK RATIO (Feed Consumption Share):")
        report.feedTankRatios.forEach { ftr ->
          val cStr = UnitUtils.formatVolume(ftr.feedConsumed, unit, settings = settings)
          val pctStr = if (ftr.percentOfTotalFeed != null) String.format(Locale.US, "%.2f%%", ftr.percentOfTotalFeed) else "-"
          appendLine("• ${ftr.tankName}: $cStr ($pctStr of total feed)")
        }
      }
      appendLine("=========================================================")
      appendLine("Generated by Tank Calc | Developed by Meherab Hossain Jihad")
    }
  }

